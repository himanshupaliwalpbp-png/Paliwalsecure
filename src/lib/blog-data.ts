export function getBlogPost(slug: string): BlogPostSummary | undefined {
  return blogPosts.find((post) => post.slug === slug);
}

export function getRelatedPosts(currentSlug: string, count: number = 3): BlogPostSummary[] {
  const currentPost = getBlogPost(currentSlug);
  if (!currentPost) return blogPosts.slice(0, count);

  const sameCategory = blogPosts.filter(
    (post) => post.slug !== currentSlug && post.category === currentPost.category
  );

  const otherCategory = blogPosts.filter(
    (post) => post.slug !== currentSlug && post.category !== currentPost.category
  );

  return [...sameCategory, ...otherCategory].slice(0, count);
}

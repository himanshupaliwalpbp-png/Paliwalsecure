// Helper functions
export function getVehicleBySlug(slug: string): Vehicle | undefined {
  return vehicles.find(v => v.slug === slug);
}

export function getVehiclesByCategory(category: 'car' | 'bike' | 'scooter'): Vehicle[] {
  return vehicles.filter(v => v.category === category);
}

export function getEVs(): Vehicle[] {
  return vehicles.filter(v => v.isEV);
}
